#!/usr/bin/env python3
"""Cutest-picture entry: draw a peekaboo kitten and write it to /output/entry.png.

Pure Python 3.13 stdlib only (zlib + struct for the PNG encoder, math for
the drawing). No network, no external files. The artwork is generated by
code, so running it twice writes identical bytes every time.

The picture: a cream kitten with huge glossy blue eyes, a pink bow and
blush cheeks peeks out at you, paws on the bottom edge, surrounded by
floating hearts and sparkles on a soft pink-peach sky.
"""
import math
import os
import struct
import zlib

W = 1024
H = 1024
DST = "/output/entry.png"


# ---------------------------------------------------------------- PNG encode
def _chunk(kind, data):
    c = struct.pack(">I", len(data)) + kind + data
    c += struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    return c


def write_png(path, w, h, rgb):
    """rgb: bytes, 3 bytes per pixel, row-major, top to bottom."""
    raw = bytearray()
    stride = w * 3
    for y in range(h):
        raw.append(0)
        raw += rgb[y * stride:(y + 1) * stride]
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n"
    png += _chunk(b"IHDR", ihdr)
    png += _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += _chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


# ------------------------------------------------------------------- drawing
def _clamp(v):
    v = int(round(v))
    return 0 if v < 0 else (255 if v > 255 else v)


class Canvas:
    def __init__(self, w, h):
        self.w = w
        self.h = h
        self.px = bytearray(w * h * 3)

    def set(self, x, y, r, g, b):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i] = _clamp(r)
            self.px[i + 1] = _clamp(g)
            self.px[i + 2] = _clamp(b)

    def blend(self, x, y, r, g, b, a):
        """Blend colour (r,g,b) with alpha a (0..1) onto pixel (x,y)."""
        if not (0 <= x < self.w and 0 <= y < self.h):
            return
        i = (y * self.w + x) * 3
        self.px[i] = _clamp(self.px[i] * (1 - a) + r * a)
        self.px[i + 1] = _clamp(self.px[i + 1] * (1 - a) + g * a)
        self.px[i + 2] = _clamp(self.px[i + 2] * (1 - a) + b * a)

    def disc(self, cx, cy, rad, r, g, b, a=1.0):
        rr = int(rad) + 1
        for dy in range(-rr, rr + 1):
            for dx in range(-rr, rr + 1):
                if dx * dx + dy * dy <= rad * rad:
                    self.blend(cx + dx, cy + dy, r, g, b, a)

    def soft_disc(self, cx, cy, rad, r, g, b, peak=0.55):
        """A radial-gradient glow disc, brightest at the centre."""
        rr = int(rad) + 1
        for dy in range(-rr, rr + 1):
            for dx in range(-rr, rr + 1):
                d2 = dx * dx + dy * dy
                if d2 <= rad * rad:
                    t = 1.0 - math.sqrt(d2) / rad
                    self.blend(cx + dx, cy + dy, r, g, b, peak * t * t)

    def ellipse(self, cx, cy, rx, ry, r, g, b, a=1.0):
        """Filled axis-aligned ellipse."""
        for dy in range(-int(ry) - 1, int(ry) + 2):
            t = dy / ry if ry else 0
            if abs(t) > 1:
                continue
            hw = rx * math.sqrt(max(0.0, 1 - t * t))
            for dx in range(-int(hw), int(hw) + 1):
                self.blend(cx + dx, cy + dy, r, g, b, a)

    def poly(self, pts, r, g, b, a=1.0):
        """Filled polygon (list of (x, y)), scanline fill."""
        ys = [p[1] for p in pts]
        for y in range(int(min(ys)), int(max(ys)) + 1):
            xs = []
            n = len(pts)
            for k in range(n):
                x0, y0 = pts[k]
                x1, y1 = pts[(k + 1) % n]
                if y0 == y1:
                    continue
                if (y0 <= y < y1) or (y1 <= y < y0):
                    t = (y - y0) / (y1 - y0)
                    xs.append(x0 + t * (x1 - x0))
            xs.sort()
            for k in range(0, len(xs) - 1, 2):
                for x in range(int(xs[k]), int(xs[k + 1]) + 1):
                    self.blend(x, y, r, g, b, a)

    def line(self, x0, y0, x1, y1, r, g, b, a=1.0, w=2):
        """A line drawn as a chain of small discs."""
        steps = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
        for s in range(steps + 1):
            t = s / steps if steps else 0
            x = int(x0 + (x1 - x0) * t)
            y = int(y0 + (y1 - y0) * t)
            self.disc(x, y, w, r, g, b, a)

    def arc(self, cx, cy, rad, a0, a1, r, g, b, a=1.0, w=2):
        """An arc of a circle, angles in radians."""
        steps = max(8, int(abs(a1 - a0) * rad))
        px = py = None
        for s in range(steps + 1):
            t = a0 + (a1 - a0) * s / steps
            x = int(cx + rad * math.cos(t))
            y = int(cy + rad * math.sin(t))
            if px is not None:
                self.line(px, py, x, y, r, g, b, a, w)
            px, py = x, y

    def heart(self, cx, cy, s, r, g, b, a=1.0):
        """A small heart: two discs on top, a triangle below."""
        self.disc(int(cx - s * 0.45), int(cy - s * 0.15), s * 0.52, r, g, b, a)
        self.disc(int(cx + s * 0.45), int(cy - s * 0.15), s * 0.52, r, g, b, a)
        self.poly([(cx - s * 0.95, cy - s * 0.05),
                   (cx + s * 0.95, cy - s * 0.05),
                   (cx, cy + s * 1.05)], r, g, b, a)

    def sparkle(self, cx, cy, s, r, g, b, a=1.0):
        """A four-point star sparkle."""
        self.poly([(cx, cy - s), (cx + s * 0.22, cy - s * 0.22),
                   (cx + s, cy), (cx + s * 0.22, cy + s * 0.22),
                   (cx, cy + s), (cx - s * 0.22, cy + s * 0.22),
                   (cx - s, cy), (cx - s * 0.22, cy - s * 0.22)],
                  r, g, b, a)


def _lerp(a, b, t):
    return a + (b - a) * t


def paint_sky(cv):
    """Soft pink-to-peach gradient, glow, bokeh and floating hearts."""
    top = (255, 227, 238)
    mid = (255, 211, 226)
    bot = (255, 201, 184)
    for y in range(H):
        t = y / (H - 1)
        if t < 0.55:
            u = t / 0.55
            r = _lerp(top[0], mid[0], u)
            g = _lerp(top[1], mid[1], u)
            b = _lerp(top[2], mid[2], u)
        else:
            u = (t - 0.55) / 0.45
            r = _lerp(mid[0], bot[0], u)
            g = _lerp(mid[1], bot[1], u)
            b = _lerp(mid[2], bot[2], u)
        for x in range(W):
            cv.set(x, y, int(r), int(g), int(b))
    # Warm glow behind the kitten.
    cv.soft_disc(512, 540, 430, 255, 250, 244, 0.55)
    cv.soft_disc(512, 540, 300, 255, 255, 255, 0.35)
    # Bokeh dots (deterministic pseudo-random placement).
    import random as _random
    rng = _random.Random(20261113)
    for _ in range(46):
        x = rng.randrange(W)
        y = rng.randrange(H)
        rad = rng.randrange(6, 26)
        col = rng.choice([(255, 255, 255), (255, 190, 210), (255, 220, 180)])
        cv.soft_disc(x, y, rad, col[0], col[1], col[2], rng.uniform(0.10, 0.28))
    # Floating hearts.
    hearts = [
        (120, 180, 26, 255, 143, 171), (905, 150, 22, 255, 120, 157),
        (90, 620, 18, 255, 170, 190), (940, 560, 24, 255, 143, 171),
        (180, 880, 20, 255, 120, 157), (860, 880, 18, 255, 170, 190),
        (700, 90, 15, 255, 190, 205), (320, 110, 14, 255, 170, 190),
    ]
    for (x, y, s, r, g, b) in hearts:
        cv.heart(x, y, s, r, g, b, 0.85)
    # Sparkles.
    for (x, y, s) in [(250, 250, 14), (770, 220, 12), (150, 420, 10),
                      (880, 380, 13), (620, 950, 11), (420, 960, 10),
                      (60, 800, 12), (970, 760, 10)]:
        cv.sparkle(x, y, s, 255, 255, 255, 0.9)
        cv.sparkle(x, y, s // 2, 255, 214, 130, 0.9)


# Kitten palette.
FUR = (255, 248, 240)
FUR_SHADE = (245, 222, 200)
FUR_DARK = (232, 200, 172)
PINK = (255, 143, 171)
PINK_DEEP = (255, 107, 157)
PINK_SOFT = (255, 179, 193)
BLUE = (91, 141, 239)
BLUE_DARK = (58, 96, 190)
INK = (58, 42, 32)
WHISKER = (190, 160, 140)


def paint_kitten(cv):
    """A cream kitten, front-facing, big glossy eyes, pink bow, paws."""
    # Soft shadow under the paws.
    cv.ellipse(512, 968, 330, 34, 244, 170, 150, 0.35)
    # Ears: outer cream triangles, inner pink triangles.
    cv.poly([(312, 400), (452, 352), (344, 196)], FUR[0], FUR[1], FUR[2])
    cv.poly([(712, 400), (572, 352), (680, 196)], FUR[0], FUR[1], FUR[2])
    cv.poly([(340, 372), (424, 340), (356, 240)], PINK_SOFT[0], PINK_SOFT[1], PINK_SOFT[2])
    cv.poly([(684, 372), (600, 340), (668, 240)], PINK_SOFT[0], PINK_SOFT[1], PINK_SOFT[2])
    # Head: a warm rim first (depth), then the cream face.
    cv.ellipse(512, 552, 280, 250, FUR_SHADE[0], FUR_SHADE[1], FUR_SHADE[2])
    cv.ellipse(512, 544, 272, 242, FUR[0], FUR[1], FUR[2])
    # Forehead tuft: three tiny cream spikes.
    cv.poly([(470, 318), (486, 282), (500, 316)], FUR[0], FUR[1], FUR[2])
    cv.poly([(500, 316), (516, 280), (530, 318)], FUR[0], FUR[1], FUR[2])
    cv.poly([(528, 318), (544, 284), (556, 320)], FUR[0], FUR[1], FUR[2])
    # Blush cheeks (soft, under the eyes).
    cv.ellipse(330, 652, 46, 28, PINK[0], PINK[1], PINK[2], 0.55)
    cv.ellipse(694, 652, 46, 28, PINK[0], PINK[1], PINK[2], 0.55)
    # Eyes: dark rim, blue iris, black pupil, big glossy highlights.
    for ex in (405, 619):
        cv.disc(ex, 545, 62, INK[0], INK[1], INK[2])
        cv.disc(ex, 545, 56, BLUE[0], BLUE[1], BLUE[2])
        cv.disc(ex, 545, 40, BLUE_DARK[0], BLUE_DARK[1], BLUE_DARK[2])
        cv.disc(ex, 545, 29, 20, 18, 28)
        cv.disc(ex - 15, 528, 17, 255, 255, 255)
        cv.disc(ex + 13, 560, 8, 255, 255, 255, 0.95)
        cv.disc(ex - 2, 516, 5, 255, 255, 255, 0.9)
    # Tiny eyebrows, barely there.
    cv.arc(405, 470, 34, math.radians(200), math.radians(340),
           FUR_DARK[0], FUR_DARK[1], FUR_DARK[2], 0.8, 3)
    cv.arc(619, 470, 34, math.radians(200), math.radians(340),
           FUR_DARK[0], FUR_DARK[1], FUR_DARK[2], 0.8, 3)
    # Nose: a small pink heart, upside-down triangle with rounded top.
    cv.poly([(496, 636), (528, 636), (512, 660)], PINK_DEEP[0], PINK_DEEP[1], PINK_DEEP[2])
    cv.disc(500, 638, 8, PINK_DEEP[0], PINK_DEEP[1], PINK_DEEP[2])
    cv.disc(524, 638, 8, PINK_DEEP[0], PINK_DEEP[1], PINK_DEEP[2])
    # Mouth: a tiny "w" under the nose.
    cv.arc(500, 668, 14, math.radians(20), math.radians(160),
           INK[0], INK[1], INK[2], 0.9, 3)
    cv.arc(524, 668, 14, math.radians(20), math.radians(160),
           INK[0], INK[1], INK[2], 0.9, 3)
    # Whiskers: three thin lines each side.
    for (x0, y0, x1, y1) in [(296, 616, 178, 592), (292, 640, 172, 640),
                             (298, 664, 184, 688)]:
        cv.line(x0, y0, x1, y1, WHISKER[0], WHISKER[1], WHISKER[2], 0.75, 2)
    for (x0, y0, x1, y1) in [(728, 616, 846, 592), (732, 640, 852, 640),
                             (726, 664, 840, 688)]:
        cv.line(x0, y0, x1, y1, WHISKER[0], WHISKER[1], WHISKER[2], 0.75, 2)
    # Pink bow on the right ear.
    cv.poly([(648, 300), (592, 262), (592, 338)], PINK_DEEP[0], PINK_DEEP[1], PINK_DEEP[2])
    cv.poly([(648, 300), (704, 262), (704, 338)], PINK_DEEP[0], PINK_DEEP[1], PINK_DEEP[2])
    cv.disc(648, 300, 15, PINK[0], PINK[1], PINK[2])
    cv.disc(648, 300, 7, 255, 255, 255, 0.9)
    # Paws peeking at the bottom edge, with pink toe beans.
    for px in (398, 626):
        cv.ellipse(px, 884, 78, 52, FUR[0], FUR[1], FUR[2])
        cv.ellipse(px, 884, 78, 52, FUR_SHADE[0], FUR_SHADE[1], FUR_SHADE[2], 0.25)
        for (bx, by) in [(px - 34, 862), (px, 854), (px + 34, 862)]:
            cv.disc(bx, by, 11, PINK[0], PINK[1], PINK[2], 0.9)
        cv.ellipse(px, 892, 20, 13, PINK[0], PINK[1], PINK[2], 0.9)


def main():
    cv = Canvas(W, H)
    paint_sky(cv)
    paint_kitten(cv)
    os.makedirs("/output", exist_ok=True)
    write_png(DST, W, H, bytes(cv.px))
    size = os.path.getsize(DST)
    if size > 1024 * 1024:
        raise SystemExit(f"output too large: {size} bytes")
    print(f"wrote {DST} ({size} bytes)")


if __name__ == "__main__":
    main()
